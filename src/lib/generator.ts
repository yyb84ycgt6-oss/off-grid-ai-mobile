/**
 * API Forge — code generation + live runtime factories.
 *
 * generateBotScript / generateMiniAI emit deployable handler source
 * (route-handler style, following the serverless-template function
 * layout and cloudnative-template validation-error phrasing).
 *
 * createBotHandler / createMiniAIHandler return LIVE handlers that run
 * in-app immediately — the generated entity API works the moment the
 * Forge produces it, no deploy step required.
 */

import { ApiOperation, EntityDescriptor, ForgeHandler, GeneratedApi } from './types';

/* ------------------------------------------------------------------ */
/* Validation (cloudnative-template error phrasing)                    */
/* ------------------------------------------------------------------ */

export function validatePayload(
  entity: EntityDescriptor,
  payload: Record<string, unknown>,
  partial = false,
): string[] {
  const errors: string[] = [];
  for (const field of entity.fields) {
    const value = payload[field.name];
    if (value === undefined || value === null) {
      if (field.required && !partial && field.semantic !== 'id' && field.semantic !== 'date') {
        errors.push(`${field.name} is required`);
      }
      continue;
    }
    const t = typeof value;
    if (field.semantic === 'number' && t !== 'number') {
      errors.push(`${field.name} must be of type number`);
    } else if (field.semantic === 'boolean' && t !== 'boolean') {
      errors.push(`${field.name} must be of type boolean`);
    } else if (
      ['text', 'freetext', 'email', 'id', 'ref', 'enum'].includes(field.semantic) &&
      t !== 'string'
    ) {
      errors.push(`${field.name} must be of type string`);
    }
    if (field.semantic === 'email' && t === 'string' && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(value as string)) {
      errors.push(`${field.name} must be a valid email`);
    }
  }
  return errors;
}

