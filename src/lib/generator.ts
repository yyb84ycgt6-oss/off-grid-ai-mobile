/** Signature of the chat function the mini AI routes through (freeAIChat). */
export type ChatFn = (
  messages: { role: 'system' | 'user' | 'assistant'; content: string }[],
  options?: { model?: string; provider?: string },
) => Promise<{ content: string }>;

export function buildMiniAIContract(entity: EntityDescriptor): string {
  const fieldLines = entity.fields
    .map((f) => `- ${f.name}: ${f.type}${f.required ? '' : ' (optional)'} [${f.semantic}]`)
    .join('\n');
  return `You are the ${entity.name} API — a mini AI generated by API Forge.
You manage ${entity.name} records with this schema:
${fieldLines}

Rules:
- Respond ONLY with a JSON object: {"ok": true, "result": ...} or {"ok": false, "error": "..."}.
- Validate every input against the schema before acting.
- For "query" operations, interpret natural-language filters against the record set you are given.
- Never invent fields that are not in the schema.`;
}

export function generateMiniAI(entity: EntityDescriptor, ops: ApiOperation[]): GeneratedApi {
  const E = entity.name;
  const code = `// ${E} API — mini AI generated by API Forge
// LLM-backed adapter through the Free AI router (Groq → OpenRouter → Ollama).
import { createMiniAIHandler, buildMiniAIContract } from '@/lib/apiForge/generator';
import { freeAIChat } from '@/lib/freeAI/client';
import { ${E}Entity } from './entities';

export const ${E}Api = createMiniAIHandler(${E}Entity, (messages, options) =>
  freeAIChat(messages, options),
);

// System contract shipped to the model on every call:
/*
${buildMiniAIContract(entity)}
*/
// Operations: ${ops.join(', ')}
`;
  return {
    entity: E,
    verdict: 'mini-ai',
    operations: ops,
    code,
    generatedAt: new Date().toISOString(),
  };
}

export function createMiniAIHandler(entity: EntityDescriptor, chat: ChatFn): ForgeHandler {
  // The mini AI keeps the same deterministic store underneath — the LLM
  // interprets intent (especially query), the store stays authoritative.
  const bot = createBotHandler(entity);
  const contract = buildMiniAIContract(entity);

  return {
    entity: entity.name,
    verdict: 'mini-ai',
    async invoke(op, payload = {}) {
      if (op !== 'query') return bot.invoke(op, payload);

      const rows = (await bot.invoke('list')) as unknown[];
      const question = String(payload.q ?? payload.where ?? '');
      const reply = await chat([
        { role: 'system', content: contract },
        {
          role: 'user',
          content: `Operation: query\nFilter: ${question}\nRecords: ${JSON.stringify(rows)}`,
        },
      ]);
      try {
        const parsed = JSON.parse(reply.content);
        if (parsed.ok === false) throw new Error(parsed.error);
        return parsed.result ?? parsed;
      } catch {
        // Model returned non-JSON — fall back to the deterministic path.
        return bot.invoke('query', typeof payload.where === 'object' ? payload : {});
      }
    },
  };
}
