export function generateBotScript(entity: EntityDescriptor, ops: ApiOperation[]): GeneratedApi {
  const E = entity.name;
  const code = `// ${E} API — bot script generated by API Forge
// Deterministic CRUD. Validation follows cloudnative-template conventions.
import { createBotHandler } from '@/lib/apiForge/generator';
import { ${E}Entity } from './entities';

export const ${E}Api = createBotHandler(${E}Entity);

// Route table (mount in any Express/Fastify/edge router):
${ops
  .map((op) => {
    switch (op) {
      case 'list':   return `// GET    /${E}s          -> ${E}Api.invoke('list')`;
      case 'get':    return `// GET    /${E}s/:id      -> ${E}Api.invoke('get', { id })`;
      case 'create': return `// POST   /${E}s          -> ${E}Api.invoke('create', body)`;
      case 'update': return `// PATCH  /${E}s/:id      -> ${E}Api.invoke('update', { id, ...body })`;
      case 'delete': return `// DELETE /${E}s/:id      -> ${E}Api.invoke('delete', { id })`;
      case 'query':  return `// POST   /${E}s/query    -> ${E}Api.invoke('query', { where })`;
    }
  })
  .join('\n')}
`;
  return {
    entity: E,
    verdict: 'bot-script',
    operations: ops,
    code,
    generatedAt: new Date().toISOString(),
  };
}

export function createBotHandler(entity: EntityDescriptor): ForgeHandler {
  const rows = new Map<string, Record<string, unknown>>();
  let seq = 0;

  return {
    entity: entity.name,
    verdict: 'bot-script',
    async invoke(op, payload = {}) {
      switch (op) {
        case 'list':
          return [...rows.values()];
        case 'get': {
          const row = rows.get(String(payload.id));
          if (!row) throw new Error(`${entity.name} not found`);
          return row;
        }
        case 'create': {
          const errors = validatePayload(entity, payload);
          if (errors.length) throw new Error(errors.join('; '));
          const id = payload.id != null ? String(payload.id) : `${entity.name}-${++seq}`;
          const row = { ...payload, id, createdAt: new Date().toISOString() };
          rows.set(id, row);
          return row;
        }
        case 'update': {
          const id = String(payload.id);
          const existing = rows.get(id);
          if (!existing) throw new Error(`${entity.name} not found`);
          const errors = validatePayload(entity, payload, true);
          if (errors.length) throw new Error(errors.join('; '));
          const row = { ...existing, ...payload, id, updatedAt: new Date().toISOString() };
          rows.set(id, row);
          return row;
        }
        case 'delete': {
          const id = String(payload.id);
          if (!rows.delete(id)) throw new Error(`${entity.name} not found`);
          return { deleted: id };
        }
        case 'query': {
          const where = (payload.where ?? {}) as Record<string, unknown>;
          return [...rows.values()].filter((row) =>
            Object.entries(where).every(([k, v]) => row[k] === v),
          );
        }
        default:
          throw new Error(`unsupported operation: ${op}`);
      }
    },
  };
}

